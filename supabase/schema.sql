create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (char_length(username) between 2 and 24),
  total_xp integer not null default 0 check (total_xp between 0 and 100000),
  completed_modules integer not null default 0 check (completed_modules between 0 and 15),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.module_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  module_id text not null,
  completed_stages integer not null default 0 check (completed_stages between 0 and 2),
  updated_at timestamptz not null default now(),
  primary key (user_id, module_id)
);

create table if not exists public.practice_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id text not null,
  answer text not null check (char_length(answer) <= 12000),
  score integer not null check (score between 0 and 100),
  feedback jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.module_progress enable row level security;
alter table public.practice_attempts enable row level security;

drop policy if exists "Profiles are publicly readable" on public.profiles;
create policy "Profiles are publicly readable"
  on public.profiles for select
  to anon, authenticated
  using (true);

drop policy if exists "Users create their own profile" on public.profiles;
create policy "Users create their own profile"
  on public.profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

